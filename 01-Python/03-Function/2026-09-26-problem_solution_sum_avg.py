# ■ 문제 요약
#  공백으로 구분된 정수들을 입력받아 리스트로 만든 후, 총합과 정수 나눗셈(소수점 이하 버림 //) 기반의 평균을 구하여
# (합, 평균) 형태의 튜플로 반환하는 sum_avg(nums) 함수를 작성하고, 이를 언패킹하여 한 줄로 출력하는 문제입니다
# ==============================================================
# ■ Algorithm
# 정수형 입력값을 리스트로 만들고 합과 평균을 계산하는 함수 작성 후 반환값 출력
# ==============================================================

def sum_avg(nums):
    """ 정수 리스트의 합과 평균을 반환
    Args:
        nums(list): 정수 리스트
    Returns:
        tuple: (합, 평균)
    """
    total = sum(nums)
    return total, total // len(nums)

nums = list(map(int, input().split()))

# 반환받은 튜플을 언패킹하여 공백으로 구분해 출력
print(*sum_avg(nums))

