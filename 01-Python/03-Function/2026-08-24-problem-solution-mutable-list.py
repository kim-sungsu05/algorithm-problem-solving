# ■ 문제 요약
# 가변 객체(Mutable Object)인 리스트의 특성을 이용해, 매개변수로 전달받은 리스트에 정수 99를 추가하는 
# 함수 append_99(lst)를 정의하고 원본 리스트의 변화를 확인하는 문제입니다.
# ==============================================================
# ■ Algorithm
# 전역변수 nums에 정수 99를 추가하는 함수를 작성 후 반환값 출력
# ==============================================================

nums = [int(x) for x in input().split()]

def append_99(lis):
    """
    전역변수 nums에 99를 추가하는 함수입니다.

    Args:
        lis(list): 99를 추가할 리스트
    Returns:
        None
    """
    # 리스트는 가변 객체이기 때문에 global 키워드를 쓰지 않더라도,
    # 함수 안에서 내용을 수정하면 같은 객체를 가리키는 원본도 함께 바뀐다.
    lis.append(99)

append_99(nums)

print(nums)

