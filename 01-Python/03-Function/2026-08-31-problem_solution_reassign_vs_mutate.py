# ■ 문제 요약
# 리스트 매개변수를 재할당(lst = [...])할 때와 내부 원소를 변형(lst.append(...))할 때,
# 원본 리스트(nums)에 미치는 영향의 차이를 확인하는 문제입니다.
# ==============================================================
# ■ Algorithm
# 지역변수 내에 새 지역리스트를 만드는 함수와 원본 리스트에 0을 추가하는 함수 정의 후 출력
# ==============================================================

nums = [int(x) for x in input().split()]


def reassign(lst):
    """
    매개변수 lst를 새로운 지역변수로 할당하는 함수입니다
    Args:
        lst(list): 입력값 nums
    Returns:
        None
    """
    # 지역 변수 내에서 새로운 리스트를 참조하기 때문에 원본은 바뀌지 않는다
    lst = [0, 0, 0]

def mutate(lst):
    """
    전역변수 nums에 0을 append하는 함수입니다
    Args:
        lst(list): 전역변수 nums
    Returns:
        None
    """
    # 같은 객체를 변형하므로 원본이 바뀐다
    lst.append(0)

reassign(nums)
print(nums)

mutate(nums)
print(nums)

