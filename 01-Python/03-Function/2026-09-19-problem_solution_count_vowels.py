# ■ 문제 요약
# 알파벳 소문자로만 이루어진 문자열을 입력받아, 내부에 포함된 모음(a, e, i, o, u)의 총 개수를 계산하여 반환하는 count_vowels(s) 함수를 구현하는 문제입니다.
# ==============================================================
# ■ Algorithm
# 영어 소문자 문자열 입력값을 인자값으로 하여 모음의 개수를 반환하는 함수 정의 후 반환값 호출
# ==============================================================

def count_vowels(s):
    """영어 소문자 문자열의 모음 개수를 반환하는 함수입니다
    Args:
        s(str): 영어 소문자 문자열
    Returns:
        int: 모음의 개수
    """
    return sum(1 for char in s if char in 'aeiou')

s = input()

print(count_vowels(s))

# ==============================================================
# ■ 개선점
# 탐색 속도 최적화 (frozenset): 비교 대상을 단순 문자열 'aeiou'에서 불변 집합인 frozenset으로 변경하여, 
# 대용량 문자열 입력 시 시간 복잡도를 O(n)에서 O(1) 수준으로 대폭 단축. 
# ==============================================================
# ■ frozenset 개선 버전

s = input()

# 영어 소문자 문자열 입력값을 인자값으로 하여 모음의 개수를 반환하는 함수 정의 후 반환값 호출
VOWELS = frozenset('aeiou') # 집합을 상수로 분리해 O(1)로 개선

def count_vowels(s):
    return sum(1 for char in s if char in VOWELS) # VOWELS 집합으로 검사

print(count_vowels(s))
