def is_palindrome(s):
    """ 문자열의 회문인지 여부에 따라 불리언값으로 반환하는 함수입니다
    Args:
        s(str): 입력값 문자열
    Returns:
        bool: 회문 여부
    Examples:
        >>> is_palindrome('racecar')  # True
        >>> is_palindrome('hello')    # False
    """
