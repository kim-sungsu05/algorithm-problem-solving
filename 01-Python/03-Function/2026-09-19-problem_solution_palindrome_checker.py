# ■ 문제 요약
# 입력받은 문자열을 거꾸로 뒤집은 결과(s[::-1])가 원래 문자열과 동일한지 비교하여, 
# 회문(Palindrome)이면 True, 아니면 False를 반환하는 함수를 구현하는 문제입니다.
# ==============================================================
# ■ Algorithm
# 입력값 s의 회문 여부에 따라 불리언형으로 반환하는 함수 정의 후 반환값 출력
# ==============================================================

def is_palindrome(s):
    """ 문자열의 회문인지 여부에 따라 불리언값으로 반환하는 함수입니다
    Args:
        s(str): 입력값 문자열
    Returns:
        bool: 회문 여부
    """
    return s == s[::-1]

s = input()
print(is_palindrome(s))

