# ==============================================================
# ■ 문제 요약
# 전역변수 count와 step을 입력받은 뒤, bump() 함수 내부에서 동일한 이름의 지역변수 count에 step을 
# 할당해 반환하게 함으로써 함수 호출 시 생성되고 소멸하는 지역변수의 생명주기와 전역변수 스코프의 독립성을 검증하고 출력하는 문제입니다.
# ==============================================================
# ■ Algorithm
# 1. 함수 안에서 지역변수 count가 전역변수 step을 참조하도록 한다
# 2. 함수를 두 번 호출 후, 전역변수 count를 출력한다
# ==============================================================

parts = input().split()
count = int(parts[0])
step = int(parts[1])


def bump() -> int:
    """지역변수 count가 step을 참조하도록 만들고 count를 반환합니다.

    Args:
        없음: 지역변수 count가 전역변수 step을 참조
    Returns:
        int: step을 참조하는 지역변수 count
    """
    count = step
    return count


print(bump())
print(bump())
print(count)

