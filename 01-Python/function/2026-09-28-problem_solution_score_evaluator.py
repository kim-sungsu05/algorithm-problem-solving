# ==============================================================
# ■ 문제 요약
#  입력받은 점수 score가 유효 범위(0 ~ 100)를 벗어나면 즉시 "유효하지 않음"을 반환하며 조기 종료하고, 
# 유효 범위 내에서는 60점 이상일 때 "합격", 미만일 때 "불합격"을 반환하는 함수 evaluate(score)를 구현하는 문제입니다.
# ==============================================================
# ■ Algorithm
# 입력 범위가 0미만 100초과인 경우는 조기종료하며, 유효한 경우, 합 불합을 판정하는 함수 작성 후 반환값 출력
# ==============================================================

def evaluate(score):
    """ 점수 유효성을 검증하고 합격/불합격을 판정합니다
    Args:
        score(int): 점수
    Returns:
        str: "유효하지 않음" | "합격" | "불합격"
    """
    # 유효 범위를 벗어나면 즉시 조기 종료
    if score < 0 or score > 100:
        return "유효하지 않음"

    if score >= 60:
        return "합격"

    return "불합격"

# 점수 입력 및 평가 결과 출력
score = int(input())
print(evaluate(score))

