# ■ 문제 요약
# ​두 정수 a, b를 공백으로 구분 받아 몫(a // b)을 계산해 반환하되, 분모 b가 0인 경우 나눗셈 연산을 수행하지 않고 
# 즉시 문자열 "오류"를 반환(조기 종료)하는 함수 safe_divide를 구현하는 문제입니다.
# ==============================================================
# ■ Algorithm
# b가 0이면 함수는 "오류"를 return하고 종료해야 한다.
# return은 값을 돌려주는 동시에 함수를 종료함.
# 함수를 호출해서 반환값을 print.
# ==============================================================


def safe_divide(a, b):
    """0으로 나누는 예외를 막는 나눗셈 함수입니다
    Args:
        a(int): 피젯수
        b(int): 젯수
    Returns:
        int: 젯수가 0이 아닌 경우 나누는 값
        str: 젯수가 0일 경우 "오류"
    """
    
    if b == 0:
        return "오류"
    else:
        return a // b

a, b = [int(x) for x in input().split()]

print(safe_divide(a, b))
