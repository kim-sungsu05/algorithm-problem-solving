# ==============================================================
# ■ 문제 요약
# 별도의 입력값 없이 100부터 999까지의 수 중 각 자릿수의 3제곱의 합이 자기 자신과 같은 3자리 암스트롱 수(Armstrong number)를 찾은 뒤, 
# 첫 줄에는 3자리 암스트롱 수:, 다음 줄부터는 N = h^3 + t^3 + o^3 형식으로 출력하는 문제입니다.
# ==============================================================
# ■ Algorithm
# 1. 제너레이터를 사용하여 100~999의 수를 문자열로 변환한다
# 2. 제너레이터를 순회하며 각 인덱스를 뽑아 정수형으로 변환한다
# 3. 각 자릿수의 3제곱이 원래 수일 경우 출력
# ==============================================================

print("3자리 암스트롱 수:")

# 제너레이터로 메모리 절약
nums_100_999 = (str(num) for num in range(100, 1000))

for num in nums_100_999:

    # 각 자릿수 추출 (뒤의 숫자는 자릿수 의미)
    num_100 = int(num[0])
    num_10 = int(num[1])
    num_1 = int(num[2])

    # 원래 수와 자릿수 3제곱값이 동일한 지 비교
    if int(num) == num_100 ** 3 + num_10 ** 3 + num_1 ** 3:
        print(f"{num} = {num_100}^3 + {num_10}^3 + {num_1}^3")
        
# ==============================================================
# ■ 개선점
# 문자열 변환없이 정수 나눗셈 (//, %)으로 자릿수를 추출하는 방식을 고려해볼 수 있다
# 제너레이터 표현식 대신 for num in range(100, 1000): 을 직접 사용해도 성능차이가 거의 없다
# 제너레이터는 대용량 데이터를 다룰 때 이점을 발휘한다
# hundreds, tens, ones 같은 명칭이 더 의미가 직관적이다
# ==============================================================
# ■ 정수 나눗셈 개선 버전

hundreds = num // 100
tens = (num // 10) % 10
ones = num % 10

