# ■ 문제 요약
# 홀수 n을 입력받아 테두리는 별(*)로 이루어져 있고 안쪽은 공백으로 비어 있는 빈 다이아몬드 모양을 출력하는 문제입니다.
# ==============================================================
# ■ Algorithm
# 1. n을 2로 나누는 값으로 공백을 추가한다 1씩 공백크기를 줄이며 반복
# 2. 별은 * 반복문 변수만큼 출력
# 3. 별 사이의 공백은 반복문 변수를 더하여하여 출력
# 4. 반복이 끝난 후 가장자리를 출력
# 5. 맨 위의 반복의 역과정으로 반복하여 다이아몬드 출력
# ==============================================================

n = int(input())

# 처음 출력할 공백 초기화 수 및 처음 반복 횟수 초기화
count = n // 2
in_star_none = 0

# 다이아몬드 윗부분 삼각형 출력
for i in range(0, count):

    # 첫 줄은 별 하나 출력으로 예외 처리
    if i == 0:
        print(" " * count + "*")

    # 두번째 줄부터 별 2개씩 출력
    else:
        # 공백 출력은 모두 홀수이므로 i(1부터 시작) + in_star_none으로 출력
        print(" " * count + "*" + (" " * (i + in_star_none)) + "*")
        in_star_none += 1

    count -= 1


# 가운데 출력
print("*" + " " * (n-2) + "*")

# 카운트 변수를 다시 n // 2로 초기화
count = n // 2

# 별 사이 공백으로 출력할 in_star_none을 초기화
in_star_none *= 2
in_star_none += 1


# 카운트만큼 반복하여 * 출력
for i in range(1, count+1):

    if i == count:
        print(" " * count + "*")

    else:
        # 공백은 홀수이므로 -2 씩 하며 출력
        in_star_none -= 2
        print(" " * i + "*" + (" " * in_star_none) + "*")

# ==============================================================
# ■ 개선점
# is_star_none 변수명은 직관적으로 파악하기 어렵다. inner_space 나 inner_gap처럼
# 의미가 명확한 이름이 좋다.
# 아랫부분에서 in_star_none *= 2 gn += 1하는 방식은 위쪽 반복 결과에 의존하므로, 독립적으로 포기화하면
# 가독성과 안정성이 높아진다.
# 효율성 측면에서 위/아래를 별도 루프로 처리하는 대신 하나의 루프에서 abs(i - n//2)기반으로 
# 공백을 계산하는 방식으로도 코드를 간결하게 할 수 있다. 
# ==============================================================
# ■ 리펙토링 코드

n = int(input())

half = n // 2 # 중심에서 꼭짓점까지의 거리

# 다이아몬드 윗부분 삼각형 출력 (꼭짓점 포함)
for i in range(half + 1):
    leading_spaces = half - i  # 앞쪽 공백 수
    inner_gap = 2 * i - 1      # 별 사이 공백 수 (꼭짓점은 해당없음)
    
    if i == 0:
        # 꼭짓점: 별 하나만 출력
        print(" " * leading_spaces + "*")
    else:
        print(" " * leading_spaces + "*" + " " * inner_gap + "*")

# 다이아몬드 아랫부분 삼각형 출력 (꼭짓점 제외, 윗쪽의 역순)  
for i in range(half - 1, -1, -1):
    leading_spaces = half - i  # 앞쪽 공백 수
    inner_gap = 2 * i - 1      # 별 사이 공백 수
    
    if i == 0:
        # 꼭짓점: 별 하나만 출력
        print(" " * leading_spaces + "*")
    else:
        print(" " * leading_spaces + "*" + " " * inner_gap + "*")
