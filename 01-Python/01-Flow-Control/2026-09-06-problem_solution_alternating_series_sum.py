# ==============================================================
# ■ 문제 요약
# 정수 N을 입력받아 1 - 1/2 + 1/3 - 1/4 + ... 형태의 교대 수열에서 1항부터 N항까지 각 단계별 누적 합을 구하고,
# 이를 k항까지의 합: X.XXXX 형식(소수점 4자리까지)으로 한 줄씩 출력하는 문제입니다.
# ==============================================================
# ■ Algorithm
# 1. 입력받은 N만큼 반복한다
# 2. 반복문의 루프변수가 짝수일 때는 -, 홀수일 때는 + 연산을 한다
# (1 - 1 / 루프변수) 방식으로 연산하며 값 출력
# 3. 처음 출력은 기본값 '1.0000' 출력
# ==============================================================

N = int(input())

# 기본값 1항 출력
default_value = 1
print(f"1항까지의 합: {default_value:.4f}")

# N번 반복
for loop_val in range(2, N+1):

    # 루프변수가 짝수일 때는 - 연산
    if loop_val % 2 == 0:
        default_value -= 1 / loop_val
        print(f"{loop_val}항까지의 합: {default_value:.4f}")

    # 루프변수가 홀수일 때는 + 연산
    else:
        default_value += 1 / loop_val
        print(f"{loop_val}항까지의 합: {default_value:.4f}")
        
# ==============================================================
# ■ 개선점
# default_value라는 변수명은 '기본값'이라는 뜻이 강하기 때문에, '누적합'을 나타내는 cumlative_sum이나 running_total같은 이름이 더 의도를 잘 전달한다. 
# 1항을 반복문 밖에서 별도로 출력하는 대신, 범위를 range(1, N+1)로 설정해 반복문 안에서 통합처리하면 코드 구조가 더 간결해진다.
# 부호 결정에 `(-1) ** (loop_val + 1)` 또는 sign 변수를 활용하면 짝수/홀수 분기 없이도 표현할 수 있어 일반적인 패턴으로 확장하기 쉽다.
# ==============================================================
# ■ 리펙토링 코드

N = int(input())

cumulative_sum = 0  # '누적 합'을 명확히 나타내는 변수명으로 변경

# range(1, N+1)로 1항부터 통합 처리 — 별도 기본값 출력 불필요
for i in range(1, N + 1):
    if i % 2 == 0:
        cumulative_sum -= 1 / i  # 짝수 항: 빼기
    else:
        cumulative_sum += 1 / i  # 홀수 항: 더하기

    # 분기 밖에서 한 번만 출력 — 중복 제거
    print(f"{i}항까지의 합: {cumulative_sum:.4f}")

# ==============================================================
# ■ (-1) ** (loop_val + 1)의 원리
# -1 은 곱하는 횟수에 따라 부호가 계속 번갈아 바뀐다.

(-1)**2 == 1
(-1)**3 == -1
(-1)**4 == 1
(-1)**5 == -1

# [기존 방식] 짝수/홀수 조건문으로 분기
total = 0
if loop_val % 2 == 0:
    total -= 1 / loop_val
else:
    total += 1 / loop_val

# [개선 방식] 부호 자체를 수식에 포함
total += ((-1) ** (loop_val + 1)) * (1 / loop_val)

# ==============================================================
# ■ sign 변수 활용 방식 (부호 반전)
# 거듭제곱 연산 (**)조차 쓰지 않고 , 반복문이 돌 때마다 부호 변수에 -1을 곱해 부호를 뒤집는 방식이다.

sign = 1  # 첫 항은 +1로 시작

for loop_val in range(1, N + 1):
    total += sign * (1 / loop_val)
    sign = -sign  # 1 -> -1 -> 1 -> -1 ... 로 지속적으로 반전

# 위 방식들은, 한 줄의 수식으로 표현할 수 있어 코드 중복을 제거해주고, 수학의 시그마 기호로 표기된 수식을 코드 형태로 옮기기 훨씬 직관적이다.
