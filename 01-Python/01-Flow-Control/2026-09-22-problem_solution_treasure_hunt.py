# ==============================================================
# ■ 문제 요약
# 1부터 100 사이의 숨겨진 보물 위치(42)를 맞추는 숫자 추측 게임입니다. 
# 입력값과 보물 위치 사이의 거리 차이(cur_diff) 구간에 따라 서로 다른 힌트 메시지를 출력하고, 
# 이전 시도보다 거리가 좁혀진 경우 추가 메시지를 출력하며 정답을 맞출 때까지 반복합니다.
# ==============================================================
# ■ Algorithm
# 1. 입력값이 42(보물위치)를 정확히 입력할 때까지 반복한다
# 2. 한 번 입력할 때마다 attempt + 1 후 출력
# 3. 입력값과 보물위치의 거리 차이에 따라 분기하여 출력문 출력
# 4. 이전 시도보다 거리가 줄어들었으면 '점점 가까워지고 있어요!' 출력
# ==============================================================

treasure = 42
attempt = 0
prev_diff = 100

print("*** 보물 찾기 ***")
print("1~100 사이에 보물이 숨겨져 있습니다!")
print()

# 무한반복
while True:

    # 입력
    guess = int(input())
    attempt += 1 # 이동한 횟수 카운팅

    cur_diff = treasure - guess
    cur_diff *= -1 if cur_diff < 0 else 1 # 차가 음수일 경우 -1을 곱하여 양수값으로 변환

    # 입력값에 따라 분기하여 출력
    if cur_diff == 0:
        print(f"보물을 찾았습니다! (시도: {attempt}회)")
        break

    # 이전값과 차이 계산
    elif cur_diff in range(1, 6):
        print(f"뜨거워요! 아주 가깝워요! (시도: {attempt}회)")

    elif cur_diff in range(6, 16):
        print(f"따뜻해요! 근처에 있어요! (시도: {attempt}회)")

    elif cur_diff in range(16, 31):
        print(f"미지근해요... (시도: {attempt}회)")

    elif cur_diff >= 31:
        print(f"차가워요! 멀리 있어요! (시도: {attempt}회)")

    # 이전 시도보다 거리가 작아졌을 경우 출력
    if cur_diff < prev_diff:
        print("점점 가까워지고 있어요!")
        prev_diff = cur_diff
    else: # 거리가 커진 경우도 새로 갱신
        prev_diff = cur_diff
print(f"축하합니다! 총 {attempt}번 만에 보물을 찾았습니다!")

# ==============================================================
# ■ 개선점
# 범위 비교 연산자 단순화: in range(1, 6) 같은 객체 생성 방식 대신 <= 5, <= 15, <= 30 형태의 비교 연산자를 사용해 연산 효율과 가독성 향상
# 삼항연산자 가독성 개선 (절댓값 계산)
cur_diff = treasure - guess if treasure >= guess else guess - treasure
