# ■ 문제 요약
# 정수 N을 입력받아 2부터 N 사이의 모든 완전수(자기 자신을 제외한 약수들의 합이 자기 자신과 같은 수)를 탐색한 뒤, 
# 각 완전수를 N = d1 + d2 + ... 형식(약수들을 오름차순으로 더한 형태)으로 출력하는 문제입니다.
# ==============================================================
# ■ Algorithm
# 1. 2중반복문으로 2부터 N+1까지 순회하며 루프변수를 안쪽 반복문으로 전달한다
# 2. 1부터 바깥 반복문의 루프변수까지 반복하여 나누어 떨어지는 수(약수)를 찾는다
# 3. 약수의 총합이 바깥 루프변수와 같을 경우 출력
# ==============================================================

# 2부터 N까지 완전수를 찾아 출력하세요.
num = int(input())

# 2부터 입력값 N까지 순회
for dividend in range(2, num+1):

    factors = []

    # 1부터 1만큼 반복하여 i의 약수를 구한다
    for divisor in range(1, dividend+1):

        # 자기 자신일 경우 제외
        if divisor == dividend:
            continue

        # i가 j로 나누어떨어지는경우 divisor에 추가
        elif dividend % divisor == 0:
            factors.append(divisor)

    # 약수의 총 합이 원래 수와 같은 경우 출력
    if sum(factors) == dividend:
        print(f"{dividend} = {' + '.join(map(str, sorted(factors)))}")

# ==============================================================
# ■ 개선점
# 현재 코드는 각 숫자 n에 대해 1부터 n-1까지 모두 순회하므로 O(N^2) 복잡도를 가진다.
# N이 10,000 이상으로 커지면 속도가 눈에 띄게 느려질 수 있다. 약수는 항상 쌍으로 존재하므로 (예: 28의 약수 2와 14)
# √n까지만 탐색하면 시간복잡도를 O(N√N)로 줄일 수 있다.
# ==============================================================
# ■ 안쪽 반복문의 시간 복잡도 개선 코드

# √dividend까지만 순회하여 약수 쌍을 한 번에 수집 (O(√n)으로 개선)
for divisor in range(1, int(dividend ** 0.5) + 1):
    if dividend % divisor == 0:
        # 자기 자신 제외
        if divisor != dividend:
            factors.append(divisor)
        pair = dividend // divisor

        # 중복, 자기자신 제외
        if pair != divisor and pair != dividend:
            factors.append(pair)

