# ==============================================================
# ■ 문제 요약
# 미리 정의된 딕셔너리 리스트에서 시나리오 번호 t를 입력받아, 각 학생의 출석 문자열('O'/'X') 내 'O'의 개수와 전체 길이를 통해 
# 출석률을 계산하고 소수점 첫째 자리 형식(이름: X.X%)으로 출력하는 문제입니다.
# ==============================================================
# ■ Algorithm
# 1. 해당 시나리오 딕셔너리의 문자열에서 'O'가 몇 번 등장했는지 카운팅한다
# 2. 카운트를 문자열의 총 길이와 나누어 출석률로 만든다
# 3. 소수점 한자리까지 각각 한 줄씩 출력한다
# ==============================================================

data_sets = [
    {
        "윤서": "OOXOOOOXO",
        "지우": "OOOOOOOOX",
        "민준": "XXOOXOXOO",
        "서윤": "OOOOOOOOO",
    },
    {
        "A": "OOOXX",
        "B": "OOXXX",
        "C": "OOOOO",
    },
    {
        "혼자": "OX",
    },
]

t = int(input())
attendance = data_sets[t]

for name, record in attendance.items():

    count = record.count('O')  # 'O'가 몇 번 등장했는지 카운팅
    attendance_rate = count / len(record) * 100  # 출석률 계산

    print(f"{name}: {attendance_rate:.1f}%")

# ==============================================================
# ■ 개선점
# for문 안에서 attendance_rate = record.count('O') / len(record) * 100
# 이런 식으로 하면 변수를 줄일 수 있어 조금 더 간결해진다.
# ==============================================================