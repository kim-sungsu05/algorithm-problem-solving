# ■ 문제 요약
# 3개의 미리 정의된 시나리오 딕셔너리 중 입력받은 번호(t)의 데이터셋을 선택하고, 
# 학생별 (마지막 점수 - 첫 점수) 변동 폭이 가장 큰 학생의 이름과 변동량을 이름: +변동 형식으로 출력하는 문제입니다 (동률 시 먼저 등록된 학생 채택)
# ==============================================================
# ■ Algorithm
# 1. 0~2의 시나리오 번호를 입력받아 해당 딕셔너리를 사용한다
# 2. 각 학생을 순회하며, 마지막 점수 - 첫 점수를 계산한다
# 3. 변동이 가장 큰(높은) 학생의 점수와 이름을 출력한다
# ==============================================================

data_sets = [
    {
        "윤서": [70, 75, 80, 85],
        "지우": [90, 88, 85, 82],
        "민준": [60, 65, 75, 90],
        "서윤": [80, 80, 80, 80],
    },
    {
        "A": [70, 80, 90],
        "B": [90, 85, 80],
    },
    {
        "X": [50, 55],
    }
]

t = int(input())
students = data_sets[t]

top_name = None
top_diff = float('-inf') # 음수 무한대로 기본값을 설정하여 음수일 경우도 안전하게 갱신

for student, scores in students.items():
    score_diff = scores[-1] - scores[0] # 현재 학생의 점수 변동 값

    if score_diff > top_diff:
        top_diff = score_diff
        top_name = student

print(f"{top_name}: {top_diff:+d}")

