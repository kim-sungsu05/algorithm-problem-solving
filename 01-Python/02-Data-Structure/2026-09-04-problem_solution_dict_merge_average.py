# ==============================================================
# ■ 문제 요약
# 시나리오 번호 t(0~2)를 입력받아 미리 정의된 두 딕셔너리(d1, d2)의 키 합집합을 구한 뒤,
# 양쪽 딕셔너리에 모두 존재하는 키는 두 값의 평균을, 한쪽에만 존재하는 키는 기존 값을 그대로 적용하여 새 매핑을 만들고, 
# 키를 가나다순(유니코드 순)으로 정렬하여 키: X.X (소수점 첫째 자리) 형식으로 한 줄씩 출력하는 문제입니다.
# ==============================================================
# ■ Algorithm
# 1. 해당 시나리오의 두 딕셔너리의 키를 집합으로 만든다
# 2. 집합을 순서열로 하여 반복
# 3. d1 딕셔너리에 집합을 키값으로 하여 값을 불러온다 이때 만약 반대 딕셔너리 (d2)일 경우 반대 딕셔너리에서도 값을 불러온다
# 4. 두 값의 평균을 구하여 튜플 리스트로 저장
# 5. 반대 딕셔너리에 동일한 키가 없을 경우 그냥 값만 출력
# 6. d2분기때는 그냥 출력만 진행
# ==============================================================

# 정수 합 평균이라도 `:.1f` 로 포맷하면 "85.0" 처럼 소수점 표시.
d1_sets = [
    {"수학": 80, "영어": 75, "과학": 90},
    {"A": 80, "B": 90},
    {"X": 100, "Y": 50},
]
d2_sets = [
    {"영어": 88, "역사": 70, "과학": 80},
    {"B": 80, "C": 90},
    {},
]
t = int(input())
d1 = d1_sets[t]
d2 = d2_sets[t]

d1_d2_set = sorted(set(set(d1.keys()) | set(d2.keys())))
avg_list = []

# 두 집합을 순서열 반복
for key in d1_d2_set:

    # d1와 d2에 해당 키가 모두 있는 경우
    if key in d1 and key in d2:

        # 평균 값 저장
        avg = (d1[key] + d2[key]) / 2
        avg_list.append((key, avg))
    # d1만 있는 경우 그냥 출력
    elif key in d1 and key not in d2:
        avg_list.append((key, d1[key]))
    
    # 남아있는 d2 요소 출력
    elif key not in d1 and key in d2:
        avg_list.append((key, d2[key]))

for sub, score in avg_list:
    print(f"{sub}: {score:.1f}")

        
# ==============================================================
# ■ 개선점
# sorted(set(set(d1.keys()) | set(d2.keys()))) '|' 연산결과만으로도 집합이 반환된다
# ==============================================================
# ■ 리펙토링 코드

# 1. 두 딕셔너리의 키 합집합을 가나다순으로 정렬
# 2. 각 키에 대해 양쪽 모두 있으면 평균, 한쪽만 있으면 그 값 출력

# set(d1) | set(d2) 로 중복 set() 호출 제거 (더 간결)
all_keys = sorted(set(d1) | set(d2))

for key in all_keys:
    if key in d1 and key in d2:
        # 양쪽 모두 있는 경우: 평균 계산
        value = (d1[key] + d2[key]) / 2
    elif key in d1:
        # d1에만 있는 경우 (key not in d2 조건 생략 가능)
        value = d1[key]
    else:
        # d2에만 있는 경우
        value = d2[key]
    # avg_list 없이 바로 출력하여 불필요한 리스트 할당 제거
    print(f"{key}: {value:.1f}")
    
