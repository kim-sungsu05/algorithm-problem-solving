# ==============================================================
# ■ 문제 요약
# 두 단어를 한 줄씩 입력받아 각 단어의 글자 집합(Set)을 형성한 뒤, 
# 두 집합의 교집합 크기를 합집합 크기로 나눈 자카드 유사도(Jaccard Similarity)를 계산하여 백분율(소수점 첫째 자리)로 출력하는 문제입니다
# ==============================================================
# ■ Algorithm
# 1. word_a와 word_b 입력값을 집합으로 형변환한다
# 2. 두 집합의 교집합, 합집합을 구한 뒤, 나눈 값을 백분율로 나타낸다
# 3. 소수점 첫번째까지 출력한다
# ==============================================================

word_a = input()
word_b = input()

set_a, set_b = set(word_a), set(word_b)

intersection = set_a & set_b
union_set = set_a | set_b

# 0으로 나누기 오류 방지 (두 입력 문자열이 모두 빈 문자열인 경우)
if not union_set:
    jaccard = 100.0
else:
    jaccard = (len(intersection) / len(union_set)) * 100

print(f"인접도: {jaccard:.1f}%")

