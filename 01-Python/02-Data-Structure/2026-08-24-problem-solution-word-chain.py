# ==============================================================
# ■ 문제 요약
# 입력받은 N개의 단어가 앞 단어의 마지막 글자와 다음 단어의 첫 글자가 이어지는 끝말잇기(단어 사슬) 규칙을 만족하는지 검사하는 문제입니다.
# ==============================================================
# ■ Algorithm
# 1. 한 줄씩 입력되는 단어를 리스트로 변환한다
# 2. 단어 리스트를 인덱스로 순회하며 현재값의 마지막 글자가 다음값의 첫번째 글자와 동일한지 비교
# 3. 계속 동일한 경우 '성공' 출력, 중간에 끊길 경우 몇번째에서 끊겼는지와 해당 단어 출력
# ==============================================================

n = int(input())

# n번 단어를 입력받아 리스트로 변환
words = [input() for _ in range(n)]

count = 0

for idx in range(n-1):

    count += 1

    # 다음 단어의 앞자리와 비교
    if words[idx][-1] != words[idx+1][0]:

        # 끊길 경우 끊김 메세지 출력
        count += 1  # 끊기는 단어는 현재 카운팅보다 더 앞이므로 한 번 더 카운팅 후 출력
        print(f"끊김: {count}번째 단어 '{words[idx+1]}'")
        break

else:
    print("성공")

# ==============================================================
# ■ 개선점
# count 변수 관리 방식이 다소 혼란스럽다. idx가 0부터 시작하므로 끊기는 단어의
# 인덱스는 idx + 1이고 위치는 idx + 2이다. count를 별도로 관리하는 대신,
# idx + 2를 직접 사용하는 것이 더 정확하다.
# ==============================================================
# ■ 리펙토링 코드
n = int(input())
words = [input() for _ in range(n)] 

for idx in range(n - 1):
    # 다음 단어의 앞자리와 비교
    if words[idx][-1] != words[idx + 1][0]:
        # 끊기는 단어의 1-based 위치는 idx + 2 (idx는 0-based이고 끊기는 단어는 그 다음))
        break_position = idx + 2
        print(f"끊김: {break_position}번째 단어 '{words[idx + 1]}'")
        break
else:
    print("성공")
