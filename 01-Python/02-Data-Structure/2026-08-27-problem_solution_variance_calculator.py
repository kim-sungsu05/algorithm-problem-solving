# ==============================================================
# ■ 문제 요약
# 시나리오 번호 0~2를 입력받아 지정된 점수 리스트의 평균, 분산, 표준편차를 계산하고
# 각각 소수점 첫째 자리까지 출력하는 문제입니다.
# ==============================================================
# ■ Algorithm
# 해당 시나리오 리스트를 사용하여 리스트 각 요소의 평균, 분산, 표준 편차를 출력한다
# ==============================================================

data_sets = [
    [85, 92, 65, 78, 95],
    [80, 90, 70],
    [50, 50, 50],
]
t = int(input())
scores = data_sets[t]


avg = sum(scores) / len(scores)
print(f"평균: {avg:.1f}")


# 시나리오 리스트를 순회하여 분산 계산
component_variance = [(score - avg) ** 2 for score in scores]
variance = sum(component_variance) / len(scores)


# 분산: 데이터가 얼마나 넓게 퍼져있는지 즉, 데이터의 일정한 정도 클 수록 데이터의 격차가 크다
print(f"분산: {variance:.1f}")


# 표준편차: 분산에 루트를 씌워 제곱때문에 커진 단위를 다시 돌려놓은 결과
print(f"표준편차: {variance ** 0.5:.1f}")

# ==============================================================
# ■ 개선점
# component_variance라는 중간 변수를 따로 만들지 않고 분산 계산을 제너레이터 표현식으로
# 합칠 수 있다. 제너레이터 표현식은 메모리를 약간 아낄 수 있다.

# ==============================================================
# ■ 수정 코드
# 제너레이터 표현식

variance = sum((score - avg) ** 2 for score in scores) / len(scores)

# ==============================================================
# ■ 제너레이터(Generator)란?
# 리스트 컴프리헨션과 동일한 구조에서 대괄호 대신 소괄호를 사용하여 제너레이터 객체를 만들어내는 구문.
# 모든 결과를 메모리에 한 번에 올리지 않고 값이 필요할 때마다 하나씩 꺼내어 생성한다. (lazy evaluation)

# -대용량 데이터 처리, -일회성 데이터 소비(next()나 for문으로 끝까지 꺼내 쓰면 객체 고갈로 재사용 불가),
# -함수 인자 축소 표현 (sum(), max(), join()등의 함수 내부 인자로 넣을 때는 소괄호 생략 가능)