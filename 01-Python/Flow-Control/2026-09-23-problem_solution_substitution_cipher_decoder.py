# ==============================================================
# ■ 문제 요약
# 대문자와 공백으로 구성된 암호문(cipher)과 26개 대문자로 이루어진 치환 키(key)를 입력받아, 
# 키에서의 인덱스 위치(0 = 'A', 1 = 'B', ..)를 이용해 원문으로 복호화하는 문제였습니다. (단, 공백은 변형 없이 유지) 
# ==============================================================
# ■ Algorithm
# 1. 알파벳이 각각 인덱스가 왼쪽으로 한 칸씩 움직인 키 문자열과, 해독할 암호문을 입력받는다
# 2. 암호문을 순회하여 루프변수를 알파벳문자열의 어느 인덱스에 위치해있는지 찾는다
# 3. 찾은 인덱스 값에서 -1을 한 뒤, num_index에 저장
# 4. 다시 알파벳 문자열에 num_index를 인덱스값으로 넣어 값을 불러와 변수에 누적저장한다
# ==============================================================

cipher = input()
key = input()

decoded = ""

for char in cipher:

    if char == " ": # 공백이 있을 경우 그냥 공백만 누적함
        decoded += " "

    elif char in key:
        num_index = key.index(char) - 1
        decoded += key[num_index]

print(decoded)

# ==============================================================
# ■ 개선점
# 치환 암호 복호화 논리 수정: key.index(char) - 1 및 key[num_index] 방식은 특정 키(+1 시프트)에서만 우연히 맞았던 로직이다.
# 키에서 암호문 글자의 위치 인덱스 num_index가 곧 원문 알파벳 순서(0 =='A')를 의미하므로, chr(65 + num_index)를 사용하여 일반적인 치환 암호에서도 정확히 복호화되도록 개선
# ==============================================================
# ■ 개선 코드

decoded = ""

for char in cipher:
    if char == " ": # 공백이 있을 경우 그냥 공백만 누적함
        decoded += " "
    elif char in key:
        num_index = key.index(char) # 키에서 암호문 글자의 위치 = 원문 알파벳 인덱스
        decoded += chr(65 + num_index) # 인덱스를 알파벳 문자로 변환 (A=65)

print(decoded)
# ==============================================================