# 제약 조건 엄격 준수 (globals() 지양): 동적 변수 접근에 사용된 globals()는 내부적으로 딕셔너리를 사용하므로, '딕셔너리/함수 금지' 제약 조건 위반 위험을 방지하고자 변수 직접 제어로 개선.
