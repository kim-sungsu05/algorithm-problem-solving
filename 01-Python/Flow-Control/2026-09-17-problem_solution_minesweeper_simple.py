# ■ 문제 요약
# 리스트, 딕셔너리, 함수 사용이 금지된 제약 조건에서 순수 변수와 제어문만 활용하여 3X3 격자의 지뢰(1)및 빈 칸(0) 정보를 입력받고, 
# 빈 칸 주변 8방향의 지뢰 개수를 산출하여 출력(지뢰 위치는 *로 표시)하는 문제입니다.
# ==============================================================
# ■ Algorithm
# 1. 3*3 격자 형태로 형태가 고정되어 있으므로 입력받은 지뢰 정보를 한 줄로 출력하기 위해 2중 for문을 각각 3번 반복한다
# 2. 반복문 안에서 바깥 루프변수를 r뒤, 안쪽 루프변수를 c뒤 숫자로 입력하여 변수값을 불러온다
# 3. 주변 8칸 지뢰의 위치를 파악해야하므로 r뒤의 숫자를 -1, +1 / c뒤의 숫자를 -1, +1 하여 변수값을 불러와 값이 1일 경우, 지뢰개수 +1
# 4. 만약 r과 c의 뒤 숫자를 -1, +1 연산했을 때 -1이나 3이 나온다면 격자를 벗어난 것이므로 건너뛴다
# 5. 주변 지뢰의 개수를 출력한다
# 6. 지뢰는 `*` 를 출력한다
# ==============================================================

r0c0, r0c1, r0c2 = input().split()
r1c0, r1c1, r1c2 = input().split()
r2c0, r2c1, r2c2 = input().split()


r0c0, r0c1, r0c2 = int(r0c0), int(r0c1), int(r0c2)
r1c0, r1c1, r1c2 = int(r1c0), int(r1c1), int(r1c2)
r2c0, r2c1, r2c2 = int(r2c0), int(r2c1), int(r2c2)

# 3번 반복
for i in range(3):

    # 3번 반복
    for j in range(3):

        boom_count = 0

        # r{i}c{j} --> 변수 불러옴
        # globals는 현재 전역 심볼 테이블(모듈에 만들어진 모든 변수,함수등의 이름과 실제값을 짝지어 관리하는 내부 장부)
        # 을 딕셔너리 형태로 반환하기 때문에 문자열 키로 접근할 수 있다
        current_point = globals()[f"r{i}c{j}"]


        # 지뢰일 경우 `*` 출력
        if current_point == 1:
            
            print("*", end=" ")

        # 지뢰가 아닐 경우 해당 위치 주변 지뢰 개수 파악
        else:

            # 주변 8칸을 탐색 (r, c 뒤의 숫자를 조건문으로 격자 범위가 넘어가는 것을 방지)

            # 현재 위치에서 위쪽
            if i - 1 >= 0:
                boom_count += 1 if globals()[f"r{i - 1}c{j}"] == 1 else 0

            # 현재 위치에서 서북쪽
            if i - 1 >= 0 and j - 1 >= 0: 
                boom_count += 1 if globals()[f"r{i - 1}c{j - 1}"] == 1 else 0
   
            # 현재 위치에서 동북쪽
            if i - 1 >= 0 and j + 1 < 3:
                boom_count += 1 if globals()[f"r{i - 1}c{j + 1}"] == 1 else 0
            
            # 현재 위치에서 왼쪽
            if j - 1 >= 0:
                boom_count += 1 if globals()[f"r{i}c{j - 1}"] == 1 else 0

            # 현재 위치에서 오른쪽
            if j + 1 < 3:
                boom_count += 1 if globals()[f"r{i}c{j + 1}"] == 1 else 0

            # 현재 위치에서 아래쪽
            if i + 1 < 3:
                boom_count += 1 if globals()[f"r{i + 1}c{j}"] == 1 else 0

            # 현재 위치에서 서남쪽 
            if i + 1 < 3 and j - 1 >= 0:
                boom_count += 1 if globals()[f"r{i + 1}c{j - 1}"] == 1 else 0

            # 현재 위치에서 동남쪽
            if i + 1 < 3 and j + 1 < 3:
                boom_count += 1 if globals()[f"r{i + 1}c{j + 1}"] == 1 else 0

            print(boom_count, end=" ")
    print() 

