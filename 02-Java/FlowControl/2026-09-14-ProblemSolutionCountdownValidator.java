// ==============================================================
// ■ 문제 요약
// 1 이상 10 이하의 유효한 정수 N이 입력될 때까지 재입력을 받은 뒤, N부터 1까지 공백으로 구분하여 
// 카운트다운을 출력하고 다음 줄에 "발사"를 출력하는 문제입니다.
// ==============================================================
// ■ Algorithm
// 1. do-while문으로 1이상 10이하의 정수가 들어올 때까지 반복하여 수를 입력받는다
// 2. 조건을 충족한 정수부터 1까지 한 줄로 출력 후, 마지막에 줄바꿈하여 '발사' 출력
// ==============================================================

import java.util.Scanner;

class Main {
    public static void main(String[] args) {
        Scanner sc = new Scanner(System.in);
        int num;

        do {
            num = sc.nextInt();
        } while (num <= 0 || num > 10); // 1이상 10이하의 정수를 입력받을 때까지 반복

        for (int i = num; i >= 1; i--) {
            System.out.print(i);

            // 후행 공백 방지
            if (i > 1) {
                System.out.print(" ");
            }
        }

        // println은 출력 후 줄바꿈이기 때문에 \n으로 줄바꿈
        System.out.print("\n발사");
        sc.close();
    }
}

// ==============================================================
// ■ 개선점
// 경계값(1, 10, 11 등)을 직접 테스트 해보는 습관을 들이면 off-by-one 실수를 사전에 잡을 수 있다.
// ==============================================================
