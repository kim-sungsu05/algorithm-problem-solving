// ==============================================================
// ■ 문제 요약
// 0과 1로만 이루어진 2진수 형태의 정수(binary)를 입력받아, 
// 내장 변환 함수(Integer.parseInt 등)를 사용하지 않고 % 10과 /= 10 자릿수 추출 연산 및 
// 자릿수별 자릿값(2^0, 2^1, 2^2 ...)의 곱을 활용해 10진수로 직접 변환하여 출력하는 문제입니다.
// ==============================================================
// ■ Algorithm
// 1. 입력값 binary가 0보다 클 때까지 반복한다
// 2. binary를 % 10 연산으로 마지막 자릿수와 power값을 곱하여 result에 저장한다
// 3. power는 분기마다 2씩 곱한다 (초기값은 1)
// 4. binary에 /= 10 연산을 하여 마지막 자릿값을 제거한다
// 5. 반복 종료 후 10진수로 변환된 결과값을 출력한다
// ==============================================================

import java.util.Scanner;

// 파일명 불일치로 인해 public 제거
class Main {
    public static void main(String[] args) {
        Scanner sc = new Scanner(System.in);
        long binary = sc.nextLong();

        int power = 1;
        int result = 0;
        int bit;

        while (binary > 0) {

            bit = (int) (binary % 10); // binary의 마지막 자릿수 추출

            result += bit * power;

            power *= 2;
            binary /= 10; // binary의 마지막 자릿수 제거
        }

        System.out.println(result);
        sc.close();
    }
}

// ==============================================================
// ■ 개선점
// 실패한 테스트케이스(10000000000 → 기대값 1024, 실제 출력 1032)가 있다.
// result와 power를 int로 선언했는데, 2^10 = 1024는 int 범위 내에 있지만,
// power가 중간에 int 한계를 넘어 정수 오버플로우가 발생하면서 잘못된 값이 누적되었다
// result, power, bit을 long으로 선언하여 큰 입력값도 안전하게 처리할 수 있도록 해야한다.
// bit 변수를 while문 루프 내부에 선언하면 스코프가 더 명확해진다.
// ==============================================================