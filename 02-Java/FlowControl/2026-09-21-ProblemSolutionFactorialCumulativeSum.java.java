// ==============================================================
// ■ 문제 요약
// 정수 n을 입력받아 1!부터 n!까지의 총합(1! + 2! + ... + n!)을 구하여 출력하는 문제입니다. 
// 루프를 돌며 fact 변수에 누적 곱을 통해 팩토리얼 값을 구하고, 이 값을 다시 sum 변수에 누적하여 합산하는 구조입니다.
// ==============================================================
// ■ Algorithm
// 정수 n을 입력받아 1!부터 n!까지의 합을 출력
// ==============================================================

import java.util.Scanner;

class Main {
    public static void main(String[] args) {
        try (Scanner sc = new Scanner(System.in);) {
            int n = sc.nextInt();

            long fact = 1;
            long sum = 0;

            for (int i = 1; i <= n; i++) {
                fact *= i; // 현재값을 누적곱하여 다음 루프변수의 팩토리얼을 구함
                sum += fact; // 현재 루프변수 팩토리얼을 누적합
            }

            System.out.println("합: " + sum);

        }
    }
}

// ==============================================================
// ■ 개선점
// 오버플로우 방어 로직 고려: 입력값 N이 매우 커질 경우 long의 범위도 초과할 수 있으므로, 실제 서비스 환경이라면 BigInteger 클래스의 활용을 고려하는 것이 좋다.
