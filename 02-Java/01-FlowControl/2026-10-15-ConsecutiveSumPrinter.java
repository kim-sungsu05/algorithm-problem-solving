// ==============================================================
// ■ 문제 요약
// 정수 N을 입력받아 N행을 출력하며, 각 i행은 i부터 시작해 N개의 연속 정수를 
// 공백으로 구분하여 출력하고 끝에 = 합 형태를 붙여 출력하는 문제입니다. 
// ==============================================================
// ■ Algorithm
// 1. 바깥 반복문은 행을 출력하고 안쪽 반복문은 열을 출력한다
// 2. 안쪽 반복문의 루프변수(col)를 바깥 반복문의 루프변수(row)로 초기화한다
// 3. 안쪽 반복문에서 col을 공백 기준으로 출력하고 누적하여 합계도 출력한다
// ==============================================================

import java.util.Scanner;

// 파일명 불일치 문제로 public 제거
class Main {
    public static void main(String[] args) {
        try (Scanner sc = new Scanner(System.in)) {
            int n = sc.nextInt();
            int limit = n; // 안쪽 반복문의 조건문에 사용

            for (int row = 1; row <= n; row++) {
                int count = 0; // 안쪽 반복문 루프변수 누적합 초기화

                for (int col = row; col <= limit; col++) {
                    System.out.print(col);
                    System.out.print(" ");
                    count += col;
                }
                System.out.print("= " + count);
                System.out.println();
                limit++; // 다음 분기가 col + 1이므로 반복할 때마다 ++ 해주어 열의 개수 동기화
            }
        }
    }
}

// ==============================================================
// ■ 개선점
// 로직 단순화 및 사이드 이펙트 방지: 바깥 루프 외부에 limit 변수를 선언하고 루프마다 limit++를 조작하여 
// 열의 개수를 맞추는 방식(사이드 이펙트)을 row + i와 같은 수학적 오프셋 구조로 변경하면 코드가 훨씬 직관적으로 된다
// ==============================================================