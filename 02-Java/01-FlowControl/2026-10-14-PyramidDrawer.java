// ==============================================================
// ■ 문제 요약
// 정수 N을 입력받아 N줄의 가운데 정렬 피라미드 형태를 출력하는 문제입니다. 각 i행마다 공백이 (N - i)개, 별이 (2i - 1)개씩 출력됩니다.
// ==============================================================
// ■ Algorithm
// 1. 정수 n을 입력받아 n만큼 반복한다
// 2. 공백을 n-1 만큼 출력한다
// 3. 별은 첫출력 1, 이후 출력은 2배만큼 더 출력한다
// ==============================================================

import java.util.Scanner;
// 파일명 불일치 문제로 public 키워드 제거
class Main {
    public static void main(String[] args) {
        try (Scanner sc = new Scanner(System.in)) {
            int n = sc.nextInt();
            int addStar = 0;

            for (int i = 1; i <= n; i++) {
                System.out.print(" ".repeat(n - i)); // 공백 출력
                System.out.print("*".repeat(i + addStar)); // 별 출력
                System.out.println(); // 줄바꿈

                addStar += 1;
            }
        }
    }
}

// ==============================================================
// ■ 개선점
// 수식 명확화 (addStar 변수 제거): addStar 변수를 두고 루프마다 누적하는 방식을 썼으나, 
// 피라미드의 특성상 i번째 행의 별 개수는 항상 수학적 공식인 2i - 1로 표현할 수 있다. 
// 이를 "*".repeat(2 * i - 1)로 직관적으로 변경하여 가독성과 코드 안정성을 높일 수 있다.
// ==============================================================