// ■ 문제 요약
// 정수의 개수와 N개의 정수를 연속으로 입력받아, 이웃한 두 수의 곱을 순차적으로 비교하면서 
// 그중 가장 큰 값을 찾아 "연속 두 값의 최대 곱: <최댓값>" 형식으로 출력하는 문제입니다.
// ==============================================================
// ■ Algorithm
// 1. 첫번째 값을 입력받아 prev 변수에 저장한다
// 2. 이후 n-1만큼 반복하여 값을 입력받는다
// 3. 반복문 안에서 입력받은 값을 cur 변수에 저장한다
// 4. prev * cur 값이 max 보다 클 경우 max 갱신
// 5. cur값을 prev에 할당한다. 이 과정을 반복하여 최댓값을 찾고 출력한다
// ==============================================================

import java.util.Scanner;

// 파일명과 불일치한 문제로 인해 public 제거
class Main {
    public static void main(String[] args) {
        Scanner sc = new Scanner(System.in);
        int n = sc.nextInt();

        int prev = sc.nextInt();
        int cur;
        int max = 0;

        for (int i = 1; i < n; i++) {

            cur = sc.nextInt();

            if (prev * cur > max) {
                max = prev * cur;
            }
            // 다음 분기에서 한 칸씩 옮기며 정수를 곱하기 위해 cur값을 prev에 대입
            prev = cur;
        }

        System.out.println("연속 두 값의 최대 곱: " + max);
        sc.close();
    }
}
