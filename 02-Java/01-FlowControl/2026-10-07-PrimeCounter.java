// ==============================================================
// ■ 문제 요약
// 정수 N을 입력받아 1부터 N까지의 수 중 소수(Prime Number)의 총개수를 구하고 개수: [값] 형태로 출력하는 문제입니다.
// ==============================================================
// ■ Algorithm
// 1. 정수 N을 입력받는다
// 2. 바깥 루프를 N번 반복하고 안쪽 루프에서 바깥 루프변수가 소수인지 판별한다
// 3. 소수일 경우 즉시 안쪽 루프 중단 후, count ++
// 4. 반복이 끝난 뒤, count 값을 출력한다
// ==============================================================

import java.util.Scanner;

class Main {
    public static void main(String[] args) {
        try (Scanner sc = new Scanner(System.in)) {
            int n = sc.nextInt();
            int count = 0;

            // 1은 소수가 아니므로 2부터 시작
            for (int i = 2; i <= n; i++) {

                boolean isPrime = true;

                for (int j = 2; j * j <= i; j++) { // 루트 i로 검사하여 시간복잡도 최적화
                    if (i % j == 0) {
                        isPrime = false;
                        break;
                    }
                }

                if (isPrime) {
                    count++;
                }
            }
            System.out.println("개수: " + count);
        }
    }
}

// ==============================================================
// ■ 개선점
// 복잡도 단순화 및 가독성 향상: 원본의 이중 반복문 제어 흐름을 isPrime 메서드로 캡슐화하여 Main 및 연산 로직의 이해도를 극대화할 수 있다
