// ==============================================================
// ■ 문제 요약
// N개의 0이 아닌 정수를 입력받아, 서로 인접한 두 수의 부호(+와 -)가 한 번도 빠짐없이 번갈아 나타나는지(엄격한 교대)를 판정하여 
// 교대 또는 교대 아님을 출력하는 문제입니다.
// ==============================================================
// ■ Algorithm
// 1. n개의 정수를 공백 기준으로 입력받는다
// 2. 첫번째 입력값을 기본값으로 설정한다
// 3. 다음 입력값과 현재 입력값의 곱이 음수일 경우 alternating에 false 저장
// 4. break 없이 쭉 순회한 뒤, alternating 값에 따라 교대, 교대 아님을 출력한다
// ==============================================================

import java.util.Scanner;

// 파일명 불일치 문제로 public 제거
class Main {
    public static void main(String[] args) {
        try (Scanner sc = new Scanner(System.in)) {
            int n = sc.nextInt(); // 입력되는 정수의 개수
            int currentNum = sc.nextInt(); // 처음 입력된 정수 초기화
            String value = "교대";

            for (int i = 0; i < n-1; i++) {
                int prevNum = sc.nextInt();

                // 양수, 음수끼리 근접할 경우 곱은 항상 양수
                if (currentNum * prevNum > 0) {
                    value = "교대 아님";
                }

                currentNum = prevNum;
            }

            System.out.println(value);
        }
    }
}

// ==============================================================
// ■ 개선점
// 버플로우 방지 (안정성 강화): 코드의 currentNum * prevNum > 0 방식은 입력된 두 수의 절댓값이 매우 클 경우 
// int 자료형의 한계를 넘어 오버플로우(Overflow)를 발생시켜 잘못된 음수/양수 결과를 낼 위험이 있디.
// 이를 (previous > 0) == (current > 0)와 같이 부호의 논리 상태를 직접 비교하도록 변경하여 버그 가능성을 원천 차단하는 것이 좋다
// ==============================================================